# -*- coding: utf-8 -*-
"""角色卡评分细则 v2.0（唯一权威标准，控制台/脚本/LLM 评测均按此执行）。

五维（每维 0~100.00，精确到 0.01）：
  style 风格辨识 25%   —— 口头禅/台词是否有该角色专属印记
  fit   角色贴合 30%   —— 读起来是否像该角色本人（而不是任何角色都能用）
  coher 内在一致 20%   —— 前后人设统一、不跳脱
  natural 表达自然 15% —— 无 AI 腔/客服腔/总结腔
  usable 完整可用 10%  —— 能直接以该卡驱动群聊（短话/分条/AI味禁令/沉默类必要扩展）

扣分细则（命中即维度上限）：
  无口头禅 → style ≤ 45.00；通用词口头禅（嘿嘿/哈哈/你好）→ style ≤ 70.00
  AI 套话（综上所述/总而言之/有什么可以帮您/首先其次…）→ natural ≤ 65.00
  "AI助手/客服/为您服务"式口吻 → fit ≤ 60.00
  人设换任何角色都能用 → fit ≤ 50.00
  示例占位"（按你的风格）" → usable ≤ 75.00
  沉默类（少言角色）无"必要对话扩展" → usable ≤ 70.00
  缺说话规则（短句/分条/AI味禁令） → usable ≤ 70.00

满分 100.00 唯一条件：**仅凭此提示词 + 一次提醒，模型即可逐句贴合该角色本人**
  （无通用话术、零 AI 腔、示例均含角色原句）；达不到一律 < 95.00（优秀 88.00~94.99）。

总分 = Σ(维度×权重)，保留 2 位小数（百分位）。
"""
from __future__ import annotations

WEIGHTS = {"style": 25, "fit": 30, "coher": 20, "natural": 15, "usable": 10}

RULES_TEXT = """【角色卡评分细则（唯一权威）】
五维评分（每维 0~100.00，精确 0.01）：
· 风格辨识(25%)：口头禅/台词是否有该角色专属印记
· 角色贴合(30%)：读起来是否像该角色本人（任何角色都能用=不行）
· 内在一致(20%)：前后人设统一不跳脱
· 表达自然(15%)：无 AI 腔/客服腔/总结腔
· 完整可用(10%)：能否直接驱动群聊（短句/分条/AI味禁令/沉默类必要扩展）
扣分上限：无口头禅→风格≤45；通用词口头禅→风格≤70；AI套话→表达≤65；
"客服/助手"口吻→贴合≤60；换角色都能用→贴合≤50；示例占位→完整≤75；
沉默类无扩展→完整≤70；缺说话规则→完整≤70。
满分 100.00 唯一条件：仅凭提示词+一次提醒即可逐句贴合本人；否则一律 <95（优秀 88~94.99）。
总分=Σ(维度×权重)，保留 2 位小数。"""


def compute(dims: dict) -> float:
    """按权重计算总分（保留百分位）。dims 缺省维度按 0。"""
    return round(sum(max(0.0, float(dims.get(k, 0))) * w / 100 for k, w in WEIGHTS.items()), 2)
